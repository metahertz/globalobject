//! Simulator for durability, availability, quota economics and attacks.
//! `cargo run --release -p globalobject-sim` prints a Markdown report to stdout.
//! Placement and quota logic come from `globalobject-policy`, the same code the control plane runs.

mod churn;
mod economics;

use globalobject_policy::{piece_availability, Policy};
use rand::{rngs::SmallRng, Rng, SeedableRng};

fn main() {
    let quick = std::env::args().any(|a| a == "--quick");
    println!("# Simulator report\n");
    println!("Generated by `cargo run --release -p globalobject-sim`. Seeds are fixed, so runs repeat exactly.\n");
    validate();
    churn::report(quick);
    economics::report();
}

/// Reproduce the analytic table with Monte Carlo, before trusting anything else here.
fn validate() {
    println!("## 1. Validation against the analytic table\n");
    println!("Independent failures, 256 independently placed chunks per file, 200-host pool.\n");
    println!("| Policy | Uptime | Analytic | Simulated | Diff |");
    println!("|---|---|---|---|---|");
    let mut rng = SmallRng::seed_from_u64(42);
    let mut worst = 0.0f64;
    for (k, n) in [(1u16, 3u16), (1, 5), (6, 12), (10, 16), (10, 20)] {
        for a in [0.8, 0.9, 0.95] {
            let analytic = piece_availability(a, k, n).powi(256);
            let trials = 40_000;
            let mut ok = 0;
            for _ in 0..trials {
                // Each chunk samples fresh host states: 200 hosts make overlap between
                // a chunk's hosts negligible relative to the per-chunk probability.
                let readable = (0..256).all(|_| {
                    let up = (0..n).filter(|_| rng.gen::<f64>() < a).count();
                    up >= k as usize
                });
                if readable {
                    ok += 1;
                }
            }
            let sim = ok as f64 / trials as f64;
            worst = worst.max((sim - analytic).abs());
            println!("| {k}-of-{n} | {:.0}% | {:.2}% | {:.2}% | {:+.2} pt |", a * 100.0, analytic * 100.0, sim * 100.0, (sim - analytic) * 100.0);
        }
    }
    println!("\nLargest difference: {:.2} percentage points. This validates the sampling, and independent failures only.\n", worst * 100.0);
    let _ = Policy::replicate3();
}
